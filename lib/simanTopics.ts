const CHELEK_TOPICS: Record<string, TopicRange[]> = {
  OrachChayim:    ORACH_CHAIM_TOPICS,
  YorehDeah:      YOREH_DEAH_TOPICS,
  EvenHaEzer:     EVEN_HAEZER_TOPICS,
  ChoshenMishpat: CHOSHEN_MISHPAT_TOPICS,
};

export function getTopicsForChelek(chelek: string): TopicRange[] {
  return CHELEK_TOPICS[chelek] ?? [];
}

export function getSimanTopic(chelek: string, siman: number): string | null {
  const ranges = CHELEK_TOPICS[chelek];
  if (!ranges) return null;
  const range = ranges.find((r) => siman >= r.from && siman <= r.to);
  return range ? range.topic : null;
}

export function getSimansByTopic(chelek: string, topic: string): number[] {
  const ranges = CHELEK_TOPICS[chelek];
  if (!ranges) return [];
  const range = ranges.find((r) => r.topic === topic);
  if (!range) return [];
  const result: number[] = [];
  for (let i = range.from; i <= range.to; i++) result.push(i);
  return result;
}
